// Package service provides server side integrations for Kerberos authentication.
package service

import (
	"fmt"
	"sync"
	"time"

	"github.com/jcmturner/gokrb5/v8/types"
)

// Replay cache is required as specified in RFC 4120 section 3.2.3

// defaultClockSkew is used when a caller supplies a non-positive retention duration.
const defaultClockSkew = 5 * time.Minute

// replayCacheCleanupInterval is how often the singleton sweeps expired entries. It is deliberately
// independent of any single caller's retention duration: the singleton is shared by every service
// in the process and its retention is the longest duration registered by any of them (see
// GetReplayCache), so a fixed sweep cadence keeps the semantics of the retention value stable.
const replayCacheCleanupInterval = time.Minute

// Cache for tickets received from clients keyed by fully qualified client name. Used to track replay of tickets.
//
// RFC 4120 section 3.2.3.1 requires the cache to remember at least the client name, the server name
// and the client's time for each presentation. The client name is the outer map key and the server
// name plus authenticator time form part of the inner key, so the combination is preserved exactly.
// This matters when the same authenticator material is presented to more than one service in the
// same process: each presentation gets its own entry instead of overwriting the previous one, and a
// replay to the service that saw the material first is still detected.
//
// The inner key also carries the authenticator's sequence number and sub-key, which are part of the
// authenticator itself and therefore identical on a byte-for-byte replay. They are included because
// RFC 4120 asks for "at least" the three fields above: two distinct authenticators generated by the
// same client in the same microsecond for the same service are not replays, and keying on the time
// alone would report them as such.
type Cache struct {
	mux     sync.Mutex
	entries map[string]clientEntries
	// retention is the longest duration registered by any caller. Guarded by mux.
	retention time.Duration
}

// clientEntries holds entries of client details sent to the service.
type clientEntries struct {
	replayMap map[replayCacheKey]replayCacheEntry
	seqNumber int64
	subKey    types.EncryptionKey
}

// replayCacheKey identifies one presentation of an authenticator to one service. The client name is
// held in the outer map, so together the two levels record the client name, the server name and the
// authenticator time required by RFC 4120 section 3.2.3.1, plus the sequence number and sub-key that
// make a presentation unique among authenticators the same client generated in the same microsecond.
type replayCacheKey struct {
	sname     string
	ctime     time.Time
	seqNumber int64
	subKeyID  string
}

// replayCacheEntry tracks when an authenticator was presented. Everything that identifies the
// presentation is part of replayCacheKey, so only the retention timestamp is stored here.
type replayCacheEntry struct {
	presentedTime time.Time
}

// Instance of the ServiceCache. This needs to be a singleton.
var replayCache *Cache
var once sync.Once

// GetReplayCache returns a pointer to the Cache singleton.
//
// d is the duration for which a presentation is remembered. The singleton is shared by every
// service in the process, and services can configure different maximum clock skews, so the cache
// retains entries for the longest duration any caller has registered: a call with a longer
// duration extends the retention from then on, while a later call with a shorter duration never
// shrinks it. Shrinking to the most recent value could evict a record while another service with a
// larger skew window is still checking against it. A non-positive duration is treated as five
// minutes, the default maximum clock skew.
func GetReplayCache(d time.Duration) *Cache {
	// Create a singleton of the ReplayCache and start a background thread to regularly clean out old entries
	once.Do(func() {
		replayCache = newCache(d)
		go replayCache.clearLoop()
	})
	replayCache.setRetention(d)
	return replayCache
}

// newCache returns an empty cache with the given retention. It does not start the cleanup loop.
func newCache(retention time.Duration) *Cache {
	return &Cache{
		entries:   make(map[string]clientEntries),
		retention: normalizeRetention(retention),
	}
}

func normalizeRetention(d time.Duration) time.Duration {
	if d <= 0 {
		return defaultClockSkew
	}
	return d
}

// setRetention raises the cache retention to d, never lowering it.
func (c *Cache) setRetention(d time.Duration) {
	d = normalizeRetention(d)
	c.mux.Lock()
	if d > c.retention {
		c.retention = d
	}
	c.mux.Unlock()
}

func (c *Cache) currentRetention() time.Duration {
	c.mux.Lock()
	defer c.mux.Unlock()
	if c.retention <= 0 {
		return defaultClockSkew
	}
	return c.retention
}

// clearLoop periodically removes entries older than the cache's current retention.
func (c *Cache) clearLoop() {
	ticker := time.NewTicker(replayCacheCleanupInterval)
	defer ticker.Stop()
	for range ticker.C {
		c.ClearOldEntries(c.currentRetention())
	}
}

// authenticatorTime returns the authenticator's CTime combined with Cusec, normalized to UTC and
// stripped of any monotonic clock reading. Stripping the monotonic reading is what makes a value
// built in memory compare equal to the same value parsed from the wire when used as a map key.
func authenticatorTime(a types.Authenticator) time.Time {
	return a.CTime.UTC().Add(time.Duration(a.Cusec) * time.Microsecond).Round(0)
}

// replayKey builds the identity of a presentation. Principal name types are not significant when
// comparing names (RFC 4120 section 6.2), which PrincipalNameString preserves. The sub-key is
// compared by its key type and raw bytes so that a replayed authenticator parses to the same key
// regardless of where it was decoded.
func replayKey(sname types.PrincipalName, a types.Authenticator) replayCacheKey {
	return replayCacheKey{
		sname:     sname.PrincipalNameString(),
		ctime:     authenticatorTime(a),
		seqNumber: a.SeqNumber,
		subKeyID:  fmt.Sprintf("%d:%x", a.SubKey.KeyType, a.SubKey.KeyValue),
	}
}

// AddEntry adds an entry to the Cache.
//
// The entry is keyed on the server name and the authenticator time, so adding a presentation for
// one service never replaces the record of the same authenticator presented to another service.
func (c *Cache) AddEntry(sname types.PrincipalName, a types.Authenticator) {
	k := replayKey(sname, a)
	c.mux.Lock()
	defer c.mux.Unlock()
	c.addEntryLocked(k, a)
}

// addEntryLocked records a presentation. The caller must hold c.mux for writing.
func (c *Cache) addEntryLocked(k replayCacheKey, a types.Authenticator) {
	if c.entries == nil {
		c.entries = make(map[string]clientEntries)
	}
	cname := a.CName.PrincipalNameString()
	ce, ok := c.entries[cname]
	if !ok {
		ce = clientEntries{replayMap: make(map[replayCacheKey]replayCacheEntry)}
	}
	ce.replayMap[k] = replayCacheEntry{presentedTime: time.Now().UTC()}
	ce.seqNumber = a.SeqNumber
	ce.subKey = a.SubKey
	c.entries[cname] = ce
}

// ClearOldEntries clears entries from the Cache that are older than the duration provided.
func (c *Cache) ClearOldEntries(d time.Duration) {
	now := time.Now().UTC()
	c.mux.Lock()
	defer c.mux.Unlock()
	for ke, ce := range c.entries {
		for k, e := range ce.replayMap {
			if now.Sub(e.presentedTime) > d {
				delete(ce.replayMap, k)
			}
		}
		if len(ce.replayMap) == 0 {
			delete(c.entries, ke)
		}
	}
}

// IsReplay tests if the Authenticator provided is a replay within the duration defined. If this is
// not a replay the entry is added to the cache for tracking.
//
// The lookup and the insert happen under one lock, so when the same authenticator is presented
// concurrently exactly one caller observes it as new and every other caller sees a replay.
func (c *Cache) IsReplay(sname types.PrincipalName, a types.Authenticator) bool {
	k := replayKey(sname, a)
	c.mux.Lock()
	defer c.mux.Unlock()
	if ce, ok := c.entries[a.CName.PrincipalNameString()]; ok {
		if _, seen := ce.replayMap[k]; seen {
			return true
		}
	}
	c.addEntryLocked(k, a)
	return false
}
